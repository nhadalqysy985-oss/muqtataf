import { chromium } from 'playwright-core'
import path from 'node:path'
const root = path.resolve('muqtataf')
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1100, height: 900 } })
await page.goto('http://127.0.0.1:4178/', { waitUntil: 'networkidle' })
console.log('start disabled initially:', await page.locator('button.start-button').isDisabled())
await page.setInputFiles('input[type=file]', path.join(root, 'tests/fixtures/too-large.pdf'))
await page.waitForTimeout(300)
console.log('large files=', await page.locator('.file-row').count(), 'toast=', (await page.locator('.toast').textContent()).replace(/\s+/g,' ').trim())
await page.setInputFiles('input[type=file]', path.join(root, 'tests/fixtures/notes.txt'))
await page.waitForTimeout(300)
console.log('txt files=', await page.locator('.file-row').count(), 'toast=', (await page.locator('.toast').textContent()).replace(/\s+/g,' ').trim())
await page.setInputFiles('input[type=file]', path.join(root, 'tests/fixtures/study2.pdf'))
await page.waitForTimeout(300)
console.log('start disabled without topic:', await page.locator('button.start-button').isDisabled())
await page.fill('#topic', 'القيادة التحويلية')
console.log('start disabled with file+topic:', await page.locator('button.start-button').isDisabled())
await page.screenshot({ path: path.join(root, 'tests/screenshots/08-validation-single.png'), fullPage: false })
await browser.close()
